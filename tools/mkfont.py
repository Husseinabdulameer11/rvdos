#!/usr/bin/env python3
"""mkfont.py -- regenerate font.c with every printable ASCII glyph.

Keeps the 51 original glyphs from the current font.c byte-for-byte and adds
the ones drawn as ASCII art in font_new_glyphs.txt. The output table is in
ASCII order starting at 0x20, so font_lookup() is a subtraction instead of
a linear search.

    python3 tools/mkfont.py                 # rewrites os/font.c
    python3 tools/mkfont.py --sheet x.ppm   # also renders every glyph for checking

Already applied: os/font.c has every glyph, so running it again stops at
the "defined twice" check. Kept for the record and as a template.
"""
import os
import re, sys

def load_existing(path):
    src = open(path).read()
    glyphs = {}
    for m in re.finditer(r"\{'(\\.|.)', \{([^}]*)\}\}", src):
        ch = m.group(1)
        if ch.startswith('\\'):
            ch = ch[1:]
        glyphs[ch] = [int(x, 16) for x in m.group(2).split(',')]
    return glyphs

def load_art(path):
    lines = [l.rstrip('\n') for l in open(path) if not l.startswith('# ')]
    lines = [l for l in lines if l != '']
    glyphs, i = {}, 0
    while i < len(lines):
        ch = lines[i]
        assert len(ch) == 1, f"bad glyph header {ch!r}"
        rows = lines[i + 1:i + 8]
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
        glyphs[ch] = [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]
        i += 8
    return glyphs

def c_char(ch):
    return {"'": "\\'", "\\": "\\\\"}.get(ch, ch)

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    font_c = os.path.join(here, '..', 'os', 'font.c')
    old = load_existing(font_c)
    new = load_art(os.path.join(here, 'font_new_glyphs.txt'))
    clash = set(old) & set(new)
    assert not clash, f"glyphs defined twice: {clash}"
    allg = {**old, **new}
    missing = [chr(c) for c in range(0x20, 0x7F) if chr(c) not in allg]
    assert not missing, f"missing glyphs: {missing}"

    out = ['#include "font.h"', '',
           '/* Generated by mkfont.py: the original 51 ASCII-art-verified glyphs',
           '   plus font_new_glyphs.txt. Entry i is the character 0x20 + i, so',
           '   font_lookup() indexes directly. Edit the .txt and regenerate',
           '   rather than editing this table by hand. */',
           'const glyph_t FONT[] = {', f'/* {0x7F - 0x20} glyphs, 0x20..0x7E */']
    for c in range(0x20, 0x7F):
        ch = chr(c)
        rows = ','.join(f'0x{b:02X}' for b in allg[ch])
        out.append(f"    {{'{c_char(ch)}', {{{rows}}}}},")
    out += ['};', '',
            'const int FONT_SIZE = sizeof(FONT) / sizeof(FONT[0]);', '',
            'const unsigned char *font_lookup(char c) {',
            '    unsigned int i = (unsigned int)(unsigned char)c - 0x20u;',
            '    if (i >= (unsigned int)FONT_SIZE) i = 0;   /* unknown -> blank */',
            '    return FONT[i].rows;',
            '}', '']
    open(font_c, 'w').write('\n'.join(out))
    print(f"font.c: {len(allg)} glyphs ({len(new)} new)")

    if '--sheet' in sys.argv:
        path = sys.argv[sys.argv.index('--sheet') + 1]
        cols, scale = 16, 4
        W, H = cols * 6 * scale, 6 * 8 * scale
        px = [[(0, 0, 0)] * W for _ in range(H)]
        for c in range(0x20, 0x7F):
            i = c - 0x20
            gx, gy = (i % cols) * 6, (i // cols) * 8
            for r, bits in enumerate(allg[chr(c)]):
                for k in range(5):
                    if bits & (1 << (4 - k)):
                        for dy in range(scale):
                            for dx in range(scale):
                                px[(gy + r) * scale + dy][(gx + k) * scale + dx] = (230, 230, 230)
        with open(path, 'wb') as f:
            f.write(f'P6 {W} {H} 255\n'.encode())
            for row in px:
                f.write(bytes(v for p in row for v in p))

if __name__ == '__main__':
    main()
