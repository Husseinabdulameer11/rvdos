/* file2c -- host tool: turn text files into samples.c, the files RVDOS
 * copies onto its RAM disk at a cold start.
 *
 *   gcc -O2 -o file2c file2c.c
 *   ./file2c samples/HELLO.FLT samples/README.TXT > samples.c
 *
 * The disk name is the file's base name, uppercased. Carriage returns are
 * dropped so files edited on Windows look the same as on Linux.
 */
#include <stdio.h>
#include <string.h>
#include <ctype.h>

int main(int argc, char **argv) {
    int i;
    printf("/* generated by file2c -- do not edit; edit samples/ instead */\n");
    printf("struct sample { const char *name; const unsigned char *data; unsigned int len; };\n\n");
    for (i = 1; i < argc; i++) {
        FILE *f = fopen(argv[i], "rb");
        int c, n = 0;
        if (!f) { fprintf(stderr, "file2c: cannot open %s\n", argv[i]); return 1; }
        printf("static const unsigned char S%d[] = {", i);
        while ((c = fgetc(f)) != EOF) {
            if (c == '\r') continue;
            if (n % 16 == 0) printf("\n   ");
            printf(" %d,", c);
            n++;
        }
        printf(" 0\n};\n");
        fclose(f);
    }
    printf("\nconst struct sample SAMPLES[] = {\n");
    for (i = 1; i < argc; i++) {
        const char *base = strrchr(argv[i], '/');
        const char *b2 = strrchr(argv[i], '\\');
        char name[32];
        int k;
        if (b2 && (!base || b2 > base)) base = b2;
        base = base ? base + 1 : argv[i];
        for (k = 0; base[k] && k < 31; k++) name[k] = (char)toupper((unsigned char)base[k]);
        name[k] = 0;
        printf("    { \"%s\", S%d, sizeof S%d - 1 },\n", name, i, i);
    }
    printf("};\nconst int NSAMPLES = %d;\n", argc - 1);
    return 0;
}
