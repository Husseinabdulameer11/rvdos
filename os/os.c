/* ======================================================================= *
 *  BIOS: console                                                          *
 * ======================================================================= */
#define CELL_W 6
#define CELL_H 8

static int cur_col, cur_row;
static unsigned char fg_color, bg_color;

/* Draw one 6x8 cell straight into the framebuffer: 48 byte stores, no
   per-pixel function calls. Row 7 and column 5 are the inter-character
   gap, always background. */
static void cell_draw(int col, int row, int ch, int fg, int bg) {
    volatile unsigned char *p;
    const unsigned char *g;
    int r;
    if ((unsigned)col >= CON_COLS || (unsigned)row >= CON_ROWS) return;
    p = FB_BASE + row * (CELL_H * FB_WIDTH) + col * CELL_W;
    g = font_lookup((char)ch);
    if (FONT_DESCENDER(ch)) {                   /* tail uses the 8th row */
        p[0] = p[1] = p[2] = p[3] = p[4] = p[5] = bg;
        p += FB_WIDTH;
        for (r = 0; r < 7; r++, p += FB_WIDTH) {
            unsigned b = g[r];
            p[0] = (b & 0x10) ? fg : bg; p[1] = (b & 0x08) ? fg : bg;
            p[2] = (b & 0x04) ? fg : bg; p[3] = (b & 0x02) ? fg : bg;
            p[4] = (b & 0x01) ? fg : bg; p[5] = bg;
        }
        return;
    }
    for (r = 0; r < 7; r++) {
        unsigned b = g[r];
        p[0] = (b & 0x10) ? fg : bg;
        p[1] = (b & 0x08) ? fg : bg;
        p[2] = (b & 0x04) ? fg : bg;
        p[3] = (b & 0x02) ? fg : bg;
        p[4] = (b & 0x01) ? fg : bg;
        p[5] = bg;
        p += FB_WIDTH;
    }
    p[0] = p[1] = p[2] = p[3] = p[4] = p[5] = bg;
}

/* the cursor is an underline in the gap row, so drawing and erasing it
   never disturbs the glyph in the cell */
static void cursor_mark(int on) {
    volatile unsigned char *p;
    int i;
    if ((unsigned)cur_col >= CON_COLS || (unsigned)cur_row >= CON_ROWS) return;
    p = FB_BASE + (cur_row * CELL_H + 7) * FB_WIDTH + cur_col * CELL_W;
    for (i = 0; i < 5; i++) p[i] = on ? fg_color : bg_color;
}

static unsigned fill_word(unsigned char c) { return c * 0x01010101u; }

static void con_clear_rows(int first, int n) {
    volatile unsigned int *p = (volatile unsigned int *)(FB_BASE + first * CELL_H * FB_WIDTH);
    unsigned w = fill_word(bg_color);
    int i, words = n * CELL_H * FB_WIDTH / 4;
    for (i = 0; i < words; i++) p[i] = w;
}

/* scroll the whole text area up one row: one word-copy pass over the
   framebuffer (the CPU can read it back through port A) */
static void con_scroll(void) {
    volatile unsigned int *d = (volatile unsigned int *)FB_BASE;
    volatile unsigned int *s = d + CELL_H * FB_WIDTH / 4;
    int i, words = (CON_ROWS - 1) * CELL_H * FB_WIDTH / 4;
    for (i = 0; i < words; i++) d[i] = s[i];
    con_clear_rows(CON_ROWS - 1, 1);
}

static void con_newline(void) {
    cur_col = 0;
    if (++cur_row >= CON_ROWS) { cur_row = CON_ROWS - 1; con_scroll(); }
}

static void bios_clear(void) {
    con_clear_rows(0, CON_ROWS);
    cur_col = 0; cur_row = 0;
}
static void bios_gotoxy(int col, int row) {
    if (col < 0) col = 0;
    if (col >= CON_COLS) col = CON_COLS - 1;
    if (row < 0) row = 0;
    if (row >= CON_ROWS) row = CON_ROWS - 1;
    cur_col = col; cur_row = row;
}
static void bios_putc(int c) {
    c &= 0xFF;
    if (c == '\n') { con_newline(); return; }
    if (c == '\r') { cur_col = 0; return; }
    if (c == KEY_BS) {                         /* move back and blank */
        if (cur_col > 0) cur_col--;
        else if (cur_row > 0) { cur_row--; cur_col = CON_COLS - 1; }
        cell_draw(cur_col, cur_row, ' ', fg_color, bg_color);
        return;
    }
    if (c == '\t') { do bios_putc(' '); while (cur_col & 3); return; }
    if (cur_col >= CON_COLS) con_newline();
    cell_draw(cur_col, cur_row, c, fg_color, bg_color);
    cur_col++;
}
static void bios_puts(const char *s) { while (*s) bios_putc((unsigned char)*s++); }
static void bios_fill(int col, int row, unsigned char color) {
    if ((unsigned)col >= CON_COLS || (unsigned)row >= CON_ROWS) return;
    fill_rect(col * CELL_W, row * CELL_H, CELL_W, CELL_H, color);
}
static void bios_setpal(int idx, unsigned int rgb) {
    set_palette((unsigned char)idx, (rgb >> 16) & 0xFF, (rgb >> 8) & 0xFF, rgb & 0xFF);
}

/* unsigned decimal without a divide instruction (this core has none):
   subtract powers of ten */
static const unsigned int POW10[] = {
    1000000000u, 100000000u, 10000000u, 1000000u, 100000u, 10000u, 1000u, 100u, 10u, 1u
};
static void put_uint(unsigned int v, int width) {
    char buf[11];
    int i, n = 0, started = 0;
    for (i = 0; i < 10; i++) {
        int d = 0;
        while (v >= POW10[i]) { v -= POW10[i]; d++; }
        if (d || started || i == 9) { buf[n++] = (char)('0' + d); started = 1; }
    }
    for (i = n; i < width; i++) bios_putc(' ');
    for (i = 0; i < n; i++) bios_putc(buf[i]);
}

/* ======================================================================= *
 *  BIOS: keyboard                                                         *
 *  The hardware holds one key and a second press overwrites it, so the    *
 *  BIOS drains it into a small ring whenever it gets the chance. ^C never *
 *  enters the ring: it sets a flag that SYS_BREAK reports.                *
 * ======================================================================= */
#define KQ_SIZE 16
static unsigned char kq[KQ_SIZE];
static unsigned int kq_head, kq_tail;
static int break_flag;
static unsigned int entropy;      /* stirred by how long each key took */

static void kbd_pump(void) {
    while (kbd_available()) {
        unsigned char c = (unsigned char)kbd_getchar();
        if (c == '\r') c = '\n';
        if (c == KEY_CTRL_C) { break_flag = 1; continue; }
        if (kq_head - kq_tail < KQ_SIZE) kq[kq_head++ & (KQ_SIZE - 1)] = c;
    }
}
static int key_poll(void) {
    kbd_pump();
    if (kq_head == kq_tail) return 0;
    return kq[kq_tail++ & (KQ_SIZE - 1)];
}
/* blocking read with a blinking underline cursor. ^C is returned here as
   itself, so line input can cancel. */
static int key_wait(void) {
    unsigned spin = 0;
    int c, shown = 0;
    for (;;) {
        c = key_poll();
        if (c) break;
        entropy++;
        if (break_flag) { break_flag = 0; c = KEY_CTRL_C; break; }
        if ((spin++ & 0x3FFF) == 0) { shown = !shown; cursor_mark(shown); }
    }
    cursor_mark(0);
    entropy = (entropy << 5 | entropy >> 27) ^ (unsigned)c ^ 0x9E3779B9u;
    return c;
}

/* line input with echo. Backspace edits, ESC clears, UP recalls the
   previous line, ^C cancels (-1). */
static char last_line[80];
static int bios_getline(char *buf, int size) {
    int n = 0, c;
    if (size <= 0) return 0;
    for (;;) {
        c = key_wait();
        if (c == '\n') break;
        if (c == KEY_CTRL_C) { bios_puts("^C\n"); buf[0] = 0; return -1; }
        if (c == KEY_BS || c == KEY_DEL) {
            if (n > 0) { n--; bios_putc(KEY_BS); }
        } else if (c == KEY_ESC || c == KEY_UP) {
            while (n > 0) { n--; bios_putc(KEY_BS); }
            if (c == KEY_UP) {
                int i;
                for (i = 0; last_line[i] && n < size - 1; i++) { buf[n++] = last_line[i]; bios_putc(last_line[i]); }
            }
        } else if (c >= 32 && c < 127 && n < size - 1) {
            buf[n++] = (char)c;
            bios_putc(c);
        }
    }
    buf[n] = 0;
    bios_putc('\n');
    if (n > 0) { int i; for (i = 0; i <= n && i < (int)sizeof last_line - 1; i++) last_line[i] = buf[i]; last_line[sizeof last_line - 1] = 0; }
    return n;
}

/* ======================================================================= *
 *  BIOS: RAM disk (drive A:)                                              *
 *  Lives in its own linker region that boot.s does NOT clear, so files    *
 *  survive pressing reset (the BRAM keeps its contents). A checksum tells *
 *  a warm start with intact files from a cold one with garbage.           *
 *  Files are stored back to back in directory order; deleting one slides *
 *  the later ones down, so there is never any fragmentation.              *
 * ======================================================================= */
#define DISK_MAGIC 0x31445652u   /* "RVD1" */
#define NDIR       48
#define NAME_LEN   13            /* "FILENAME.EXT" + NUL */

struct dirent { char name[16]; unsigned int size, off; };
struct disk {
    unsigned int magic, sum, used, nfiles;
    struct dirent dir[NDIR];
    unsigned char data[];
};
#define DISK      ((struct disk *)_disk_start)
#define DISK_DATA ((unsigned int)(_disk_end - _disk_start) - (unsigned int)sizeof(struct disk))

static unsigned int disk_checksum(void) {
    const unsigned int *w = (const unsigned int *)DISK;
    unsigned int s = 0x5A5A1234u, i, n;
    n = (unsigned int)(sizeof(struct disk) + DISK->used + 3) / 4;
    if (DISK->used > DISK_DATA) return ~DISK->sum;     /* corrupt header */
    for (i = 2; i < n; i++) s = (s << 1 | s >> 31) ^ w[i];   /* skip magic,sum */
    return s;
}
static void disk_seal(void) { DISK->magic = DISK_MAGIC; DISK->sum = disk_checksum(); }
static int  disk_valid(void) {
    return DISK->magic == DISK_MAGIC && DISK->nfiles <= NDIR &&
           DISK->used <= DISK_DATA && DISK->sum == disk_checksum();
}
static void disk_format(void) {
    mem_set(DISK, 0, sizeof(struct disk));
    disk_seal();
}

static int up(int c) { return (c >= 'a' && c <= 'z') ? c - 32 : c; }
static int name_char(int c) {
    return (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_' || c == '-' || c == '$';
}

/* "a:hello.flt" -> "HELLO.FLT". Wildcards (* and ?) allowed when wild is
   set. Returns 0, or FS_BADNAME. */
static int fs_norm(const char *in, char *out, int wild) {
    int n = 0, base = 0, ext = -1;
    while (*in == ' ') in++;
    if (up(in[0]) == 'A' && in[1] == ':') in += 2;
    for (; *in && *in != ' '; in++) {
        int c = up((unsigned char)*in);
        if (c == '.') {
            if (ext >= 0 || base == 0) return FS_BADNAME;
            ext = 0; out[n++] = '.';
            continue;
        }
        if (!name_char(c) && !(wild && (c == '*' || c == '?'))) return FS_BADNAME;
        if (ext >= 0) { if (++ext > 3) return FS_BADNAME; }
        else if (++base > 8) return FS_BADNAME;
        out[n++] = (char)c;
    }
    if (base == 0) return FS_BADNAME;
    if (ext == 0) n--;                       /* "NAME." == "NAME" */
    out[n] = 0;
    return FS_OK;
}

/* glob over one name field ("*" matches any run, "?" one char) */
static int glob(const char *p, const char *s) {
    if (*p == 0) return *s == 0;
    if (*p == '*') { do { if (glob(p + 1, s)) return 1; } while (*s++); return 0; }
    if (*s == 0) return 0;
    return (*p == '?' || *p == *s) && glob(p + 1, s + 1);
}
static void split(const char *name, char *base, char *ext) {
    while (*name && *name != '.') *base++ = *name++;
    *base = 0;
    if (*name == '.') name++;
    while (*name) *ext++ = *name++;
    *ext = 0;
}
/* CP/M rules: a pattern with no '.' means any extension, so DIR H*
   finds HELLO.FLT */
static int fs_match(const char *pat, const char *name) {
    char pb[16], pe[8], nb[16], ne[8];
    int has_dot = 0;
    const char *q;
    for (q = pat; *q; q++) if (*q == '.') has_dot = 1;
    split(pat, pb, pe);
    split(name, nb, ne);
    if (!has_dot) { pe[0] = '*'; pe[1] = 0; }
    return glob(pb, nb) && glob(pe, ne);
}

static int fs_find(const char *name) {
    char n[NAME_LEN];
    unsigned int i;
    if (fs_norm(name, n, 0)) return FS_NOTFOUND;
    for (i = 0; i < DISK->nfiles; i++)
        if (str_eq(DISK->dir[i].name, n)) return (int)i;
    return FS_NOTFOUND;
}
static void fs_remove(unsigned int id) {
    struct dirent *e = &DISK->dir[id];
    unsigned int off = e->off, sz = e->size, i;
    mem_move(DISK->data + off, DISK->data + off + sz, DISK->used - off - sz);
    DISK->used -= sz;
    for (i = id; i + 1 < DISK->nfiles; i++) {
        DISK->dir[i] = DISK->dir[i + 1];
        DISK->dir[i].off -= sz;
    }
    DISK->nfiles--;
    mem_set(&DISK->dir[DISK->nfiles], 0, sizeof(struct dirent));
}
static int fs_delete(const char *name) {
    int id = fs_find(name);
    if (id < 0) return FS_NOTFOUND;
    fs_remove((unsigned)id);
    disk_seal();
    return FS_OK;
}
/* create or replace. src may point into the disk itself (PIP copies a
   file), so the bytes are appended before the old copy is removed. */
static void fs_append(const char *n, const void *src, unsigned int len) {
    struct dirent *e = &DISK->dir[DISK->nfiles++];
    mem_move(DISK->data + DISK->used, src, len);
    mem_set(e->name, 0, sizeof e->name);
    str_copy(e->name, n, sizeof e->name);
    e->off = DISK->used;
    e->size = len;
    DISK->used += len;
}
static int fs_write(const char *name, const void *src, unsigned int len) {
    char n[NAME_LEN];
    int old;
    if (fs_norm(name, n, 0)) return FS_BADNAME;
    old = fs_find(n);
    if (len <= DISK_DATA - DISK->used && DISK->nfiles < NDIR) {
        /* room for both copies: append first, then drop the old one (its
           removal slides the new copy down and fixes its offset) */
        fs_append(n, src, len);
        if (old >= 0) fs_remove((unsigned)old);
    } else if (old >= 0) {
        /* tight: free the old copy first -- only safe if the new bytes
           don't live inside it */
        const unsigned char *s = (const unsigned char *)src;
        const unsigned char *o = DISK->data + DISK->dir[old].off;
        if (DISK->used - DISK->dir[old].size + len > DISK_DATA) return FS_FULL;
        unsigned int osz = DISK->dir[old].size;
        if (s + len > o && s < o + osz) return FS_FULL;
        fs_remove((unsigned)old);
        /* bytes stored after the removed file just slid down */
        if (s >= o + osz && s < DISK->data + DISK->used + osz) s -= osz;
        fs_append(n, s, len);
    } else {
        return DISK->nfiles >= NDIR ? FS_DIRFULL : FS_FULL;
    }
    disk_seal();
    return FS_OK;
}
static int fs_rename(const char *from, const char *to) {
    char n[NAME_LEN];
    int id;
    if (fs_norm(to, n, 0)) return FS_BADNAME;
    id = fs_find(from);
    if (id < 0) return FS_NOTFOUND;
    if (fs_find(n) >= 0) return FS_EXISTS;
    mem_set(DISK->dir[id].name, 0, sizeof DISK->dir[id].name);
    str_copy(DISK->dir[id].name, n, sizeof DISK->dir[id].name);
    disk_seal();
    return FS_OK;
}
static void install_samples(void) {
    int i;
    for (i = 0; i < NSAMPLES; i++) fs_write(SAMPLES[i].name, SAMPLES[i].data, SAMPLES[i].len);
}

/* ======================================================================= *
 *  BIOS: pixels                                                           *
 * ======================================================================= */
static int bios_getpix(int x, int y) {
    if ((unsigned)x >= FB_WIDTH || (unsigned)y >= FB_HEIGHT) return 0;
    return FB_BASE[y * FB_WIDTH + x];
}
static void bios_rect(long xy, long wh, int c) {
    int x = (short)(xy & 0xFFFF), y = (short)(xy >> 16);
    int w = (short)(wh & 0xFFFF), h = (short)(wh >> 16);
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > FB_WIDTH) w = FB_WIDTH - x;
    if (y + h > FB_HEIGHT) h = FB_HEIGHT - y;
    if (w > 0 && h > 0) fill_rect(x, y, w, h, (unsigned char)c);
}

/* ======================================================================= *
 *  BDOS: the syscall dispatcher                                           *
 * ======================================================================= */
static char cmd_tail[80];

long bdos_dispatch(long fn, long a1, long a2, long a3) {
    switch (fn) {
        case SYS_EXIT:     return 0;   /* co-resident: transient just returns */
        case SYS_GETC:     return key_wait();
        case SYS_PUTC:     bios_putc((int)a1); return 0;
        case SYS_POLL:     return key_poll();
        case SYS_BREAK:    { int b; kbd_pump(); b = break_flag; break_flag = 0; return b; }
        case SYS_PUTS:     bios_puts((const char *)a1); return 0;
        case SYS_CLEAR:    bios_clear(); return 0;
        case SYS_GOTOXY:   bios_gotoxy((int)a1, (int)a2); return 0;
        case SYS_FILLCELL: bios_fill((int)a1, (int)a2, (unsigned char)a3); return 0;
        case SYS_SETCOLOR: fg_color = (unsigned char)a1; bg_color = (unsigned char)a2; return 0;
        case SYS_SETPAL:   bios_setpal((int)a1, (unsigned int)a2); return 0;
        case SYS_GETXY:    return cur_col | (cur_row << 8);
        case SYS_PUTCELL:  cell_draw((int)(a1 & 0xFF), (int)((a1 >> 8) & 0xFF), (int)(a2 & 0xFF),
                                     (int)(a3 & 0xFF), (int)((a3 >> 8) & 0xFF)); return 0;
        case SYS_GETLINE:  return bios_getline((char *)a1, (int)a2);
        case SYS_FFIND:    return fs_find((const char *)a1);
        case SYS_FSIZE:    return ((unsigned long)a1 < DISK->nfiles) ? (long)DISK->dir[a1].size : -1;
        case SYS_FDATA:    return ((unsigned long)a1 < DISK->nfiles) ? (long)(DISK->data + DISK->dir[a1].off) : 0;
        case SYS_FWRITE:   return fs_write((const char *)a1, (const void *)a2, (unsigned int)a3);
        case SYS_FDELETE:  return fs_delete((const char *)a1);
        case SYS_FRENAME:  return fs_rename((const char *)a1, (const char *)a2);
        case SYS_FNAME:    if ((unsigned long)a1 >= DISK->nfiles) return -1;
                           str_copy((char *)a2, DISK->dir[a1].name, NAME_LEN); return 0;
        case SYS_FFREE:    return (long)(DISK_DATA - DISK->used);
        case SYS_PIXEL:    if ((unsigned long)a1 < FB_WIDTH && (unsigned long)a2 < FB_HEIGHT)
                               FB_BASE[a2 * FB_WIDTH + a1] = (unsigned char)a3;
                           return 0;
        case SYS_RECT:     bios_rect(a1, a2, (int)a3); return 0;
        case SYS_GETPIX:   return bios_getpix((int)a1, (int)a2);
        case SYS_ARGS:     return (long)cmd_tail;
        case SYS_VERSION:  return RVDOS_VERSION;
        case SYS_TPA:      return a1 ? (long)(_tpa_end - _tpa_start) : (long)_tpa_start;
        case SYS_RANDOM:   entropy = entropy * 1664525u + 1013904223u; return (long)entropy;
        default:           return -1;
    }
}

