static void base_palette(void) {
    bios_setpal(0, 0x000000);   /* background      */
    bios_setpal(1, 0xC0C0C0);   /* normal text     */
    bios_setpal(2, 0xFFC800);   /* highlight       */
    bios_setpal(3, 0x40C8FF);   /* title           */
    fg_color = 1; bg_color = 0;
}
static void color(int c) { fg_color = (unsigned char)c; }

static const char *skip_sp(const char *s) { while (*s == ' ') s++; return s; }
/* copy the next blank-delimited word, uppercased */
static const char *word(const char *s, char *out, int size) {
    int n = 0;
    s = skip_sp(s);
    while (*s && *s != ' ') { if (n < size - 1) out[n++] = (char)up((unsigned char)*s); s++; }
    out[n] = 0;
    return skip_sp(s);
}
static int confirm(const char *q) {
    char a[8];
    bios_puts(q); bios_puts(" (Y/N)? ");
    return bios_getline(a, sizeof a) > 0 && up(a[0]) == 'Y';
}
static void fs_report(int r) {
    switch (r) {
        case FS_NOTFOUND: bios_puts("NO FILE\n"); break;
        case FS_FULL:     bios_puts("DISK FULL\n"); break;
        case FS_DIRFULL:  bios_puts("DIRECTORY FULL\n"); break;
        case FS_BADNAME:  bios_puts("BAD FILE NAME\n"); break;
        case FS_EXISTS:   bios_puts("FILE EXISTS\n"); break;
        case FS_READONLY: bios_puts("READ ONLY (ROM)\n"); break;
        default: break;
    }
}
static const struct prog *find_prog(const char *name) {
    char n[NAME_LEN];
    int i, len;
    if (fs_norm(name, n, 0)) return 0;
    len = str_len(n);
    if (len > 4 && str_eq(n + len - 4, ".COM")) n[len - 4] = 0;
    for (i = 0; i < NPROG; i++) if (str_eq(CATALOG[i].name, n)) return &CATALOG[i];
    return 0;
}

/* --- listing helpers: ROM programs appear as read-only NAME.COM ------- */
typedef void (*list_fn)(const char *name, unsigned int size, int rom, void *ctx);
static int each_file(const char *pat, list_fn fn, void *ctx) {
    char p[NAME_LEN + 4], n[NAME_LEN + 4];
    int i, hits = 0;
    if (*pat == 0) str_copy(p, "*.*", sizeof p);
    else if (fs_norm(pat, p, 1)) { bios_puts("BAD FILE NAME\n"); return -1; }
    for (i = 0; i < NPROG; i++) {
        str_copy(n, CATALOG[i].name, sizeof n);
        str_cat(n, ".COM", sizeof n);
        if (fs_match(p, n)) { fn(n, 0, 1, ctx); hits++; }
    }
    for (i = 0; i < (int)DISK->nfiles; i++)
        if (fs_match(p, DISK->dir[i].name)) { fn(DISK->dir[i].name, DISK->dir[i].size, 0, ctx); hits++; }
    return hits;
}

/* DIR: three CP/M-style "NAME     EXT" columns per line */
static void dir_one(const char *name, unsigned int size, int rom, void *ctx) {
    int *col = (int *)ctx, i = 0, k;
    (void)size; (void)rom;
    bios_puts(*col == 0 ? "A: " : " : ");
    for (k = 0; name[i] && name[i] != '.'; i++, k++) bios_putc(name[i]);
    for (; k < 9; k++) bios_putc(' ');
    if (name[i] == '.') i++;
    for (k = 0; name[i]; i++, k++) bios_putc(name[i]);
    for (; k < 3; k++) bios_putc(' ');
    if (++*col == 3) { bios_putc('\n'); *col = 0; }
}
static void cmd_dir(const char *args) {
    int col = 0, hits = each_file(args, dir_one, &col);
    if (col) bios_putc('\n');
    if (hits == 0) bios_puts("NO FILE\n");
}

/* STAT: sizes and free space */
static void stat_one(const char *name, unsigned int size, int rom, void *ctx) {
    (void)ctx;
    if (rom) bios_puts("    ROM  ");
    else { put_uint(size, 7); bios_puts("  "); }
    bios_puts(name); bios_putc('\n');
}
static void cmd_stat(const char *args) {
    int hits;
    color(3); bios_puts("  Bytes  Name\n"); color(1);
    hits = each_file(args, stat_one, 0);
    if (hits == 0) bios_puts("NO FILE\n");
    bios_puts("A: R/W, Space: ");
    put_uint(DISK_DATA - DISK->used, 0);
    bios_puts(" of ");
    put_uint(DISK_DATA, 0);
    bios_puts(" bytes free, ");
    put_uint(DISK->nfiles, 0);
    bios_puts(" files\nTPA: ");
    put_uint((unsigned)(_tpa_end - _tpa_start), 0);
    bios_puts(" bytes\n");
}

/* TYPE: page every screenful; any key continues, ^C or Q stops */
static void cmd_type(const char *args) {
    int id, lines = 0, col = 0;
    unsigned int i, n;
    const unsigned char *d;
    char name[NAME_LEN];
    word(args, name, sizeof name);
    if (find_prog(name)) { fs_report(FS_READONLY); return; }
    id = fs_find(name);
    if (id < 0) { fs_report(FS_NOTFOUND); return; }
    d = DISK->data + DISK->dir[id].off;
    n = DISK->dir[id].size;
    for (i = 0; i < n; i++) {
        int row_done;
        bios_putc(d[i]);
        /* count screen rows, not file lines: long lines wrap */
        row_done = d[i] == '\n' || ++col == CON_COLS;
        if (row_done) col = 0;
        if (row_done && ++lines == CON_ROWS - 1) {
            int c;
            color(2); bios_puts("--MORE--"); color(1);
            c = key_wait();
            bios_puts("\r        \r");
            if (c == KEY_CTRL_C || up(c) == 'Q') return;
            lines = 0;
        }
        if ((i & 63) == 0 && (kbd_pump(), break_flag)) { break_flag = 0; bios_puts("^C\n"); return; }
    }
    if (n && d[n - 1] != '\n') bios_putc('\n');
}

/* ERA: wildcards allowed; "*.*" asks first, as CP/M did */
static void cmd_era(const char *args) {
    char p[NAME_LEN + 4];
    int i, hits = 0;
    if (*args == 0) { bios_puts("ERA WHAT?\n"); return; }
    if (fs_norm(args, p, 1)) { fs_report(FS_BADNAME); return; }
    if (find_prog(p)) { fs_report(FS_READONLY); return; }
    if (str_eq(p, "*.*") && !confirm("ALL FILES")) return;
    for (i = 0; i < (int)DISK->nfiles; )
        if (fs_match(p, DISK->dir[i].name)) { fs_remove((unsigned)i); hits++; }
        else i++;
    disk_seal();
    if (!hits) fs_report(FS_NOTFOUND);
}

/* "NEW=OLD" (CP/M) or "OLD NEW" -> two names */
static int two_names(const char *args, char *dst, char *src) {
    char a[40], b[40];
    int i, eq = -1;
    for (i = 0; args[i]; i++) if (args[i] == '=') eq = i;
    if (eq >= 0) {
        for (i = 0; i < eq && i < 39; i++) a[i] = args[i];
        a[i] = 0;
        word(a, dst, NAME_LEN + 4);
        word(args + eq + 1, src, NAME_LEN + 4);
    } else {
        word(word(args, b, sizeof b), a, sizeof a);
        str_copy(src, b, NAME_LEN + 4);
        str_copy(dst, a, NAME_LEN + 4);
    }
    return *dst && *src;
}
static void cmd_ren(const char *args) {
    char d[NAME_LEN + 4], s[NAME_LEN + 4];
    if (!two_names(args, d, s)) { bios_puts("USE: REN NEW=OLD\n"); return; }
    if (find_prog(s) || find_prog(d)) { fs_report(FS_READONLY); return; }
    fs_report(fs_rename(s, d));
}
static void cmd_pip(const char *args) {
    char d[NAME_LEN + 4], s[NAME_LEN + 4];
    int id;
    if (!two_names(args, d, s)) { bios_puts("USE: PIP NEW=OLD\n"); return; }
    if (find_prog(s) || find_prog(d)) { fs_report(FS_READONLY); return; }
    id = fs_find(s);
    if (id < 0) { fs_report(FS_NOTFOUND); return; }
    fs_report(fs_write(d, DISK->data + DISK->dir[id].off, DISK->dir[id].size));
}

static void cmd_help(void) {
    int i;
    color(3); bios_puts("BUILT-IN COMMANDS\n"); color(1);
    bios_puts(" DIR [pat]      list files (DIR *.FLT)\n"
              " STAT [pat]     sizes and free space\n"
              " TYPE file      show a text file\n"
              " ERA pat        erase files\n"
              " REN new=old    rename a file\n"
              " PIP new=old    copy a file\n"
              " CLS            clear the screen\n"
              " FORMAT         wipe A: and restore samples\n"
              " VER  HELP  HALT\n");
    color(3); bios_puts("PROGRAMS\n"); color(1);
    for (i = 0; i < NPROG; i++) {
        int k;
        bios_putc(' '); bios_puts(CATALOG[i].name);
        for (k = str_len(CATALOG[i].name); k < 15; k++) bios_putc(' ');
        bios_puts(CATALOG[i].about); bios_putc('\n');
    }
    bios_puts(" NAME           runs NAME.FLT with Flint\n");
    bios_puts("Keys: UP recalls the last line, ^C stops.\n");
}

static void banner(int warm) {
    color(3); bios_puts("RVDOS 2.0"); color(1);
    bios_puts("  RV32IM  ");
    put_uint((unsigned)(unsigned long)_disk_end >> 10, 0);   /* disk ends at top of RAM */
    bios_puts("K RAM\n");
    bios_puts(warm ? "Warm start: files kept, " : "Cold start: samples on A:, ");
    put_uint(DISK->nfiles, 0); bios_puts(" files\n");
    bios_puts("Type HELP for commands.\n\n");
}

static void run_prog(const struct prog *p, const char *tail) {
    str_copy(cmd_tail, tail, sizeof cmd_tail);
    break_flag = 0;
    p->entry();
    base_palette();
    if (p->clear_after) bios_clear();
    else if (cur_col) bios_putc('\n');
    cmd_tail[0] = 0;
}

/* one command line. Returns 0 to halt. */
static int ccp_line(const char *line) {
    char cmd[24], fname[NAME_LEN + 4];
    const char *args = word(line, cmd, sizeof cmd);
    const struct prog *p;
    int len;

    if (cmd[0] == 0) return 1;
    if (str_eq(cmd, "A:")) return 1;
    if (str_eq(cmd, "DIR"))    { cmd_dir(args); return 1; }
    if (str_eq(cmd, "STAT"))   { cmd_stat(args); return 1; }
    if (str_eq(cmd, "TYPE"))   { cmd_type(args); return 1; }
    if (str_eq(cmd, "ERA"))    { cmd_era(args); return 1; }
    if (str_eq(cmd, "REN"))    { cmd_ren(args); return 1; }
    if (str_eq(cmd, "PIP"))    { cmd_pip(args); return 1; }
    if (str_eq(cmd, "CLS"))    { bios_clear(); return 1; }
    if (str_eq(cmd, "HELP") || str_eq(cmd, "?")) { cmd_help(); return 1; }
    if (str_eq(cmd, "VER"))    { bios_puts("RVDOS 2.0, Flint 1.0\n"); return 1; }
    if (str_eq(cmd, "FORMAT")) {
        if (confirm("ERASE ALL OF A:")) { disk_format(); install_samples(); bios_puts("A: FORMATTED\n"); }
        return 1;
    }
    if (str_eq(cmd, "HALT"))   return 0;

    /* a transient: a ROM program, or NAME.FLT run by Flint */
    p = find_prog(cmd);
    if (p) { run_prog(p, args); return 1; }
    if (fs_norm(cmd, fname, 0) == FS_OK) {
        char tail[80];
        len = str_len(fname);
        if (!(len > 4 && str_eq(fname + len - 4, ".FLT"))) {
            int dot = 0, i;
            for (i = 0; fname[i]; i++) if (fname[i] == '.') dot = 1;
            if (!dot) str_cat(fname, ".FLT", sizeof fname);
        }
        if (fs_find(fname) >= 0) {
            str_copy(tail, fname, sizeof tail);
            if (*args) { str_cat(tail, " ", sizeof tail); str_cat(tail, args, sizeof tail); }
            run_prog(find_prog("FLINT"), tail);
            return 1;
        }
    }
    bios_puts(cmd); bios_puts("?\n");               /* CP/M's famous reply */
    return 1;
}

void ccp_main(void) {
    char line[80];
    int warm;

    base_palette();
    bios_clear();
    warm = disk_valid();
    if (!warm) { disk_format(); install_samples(); }
    banner(warm);

    for (;;) {
        color(1);
        bios_puts("A>");
        if (bios_getline(line, sizeof line) < 0) continue;
        if (!ccp_line(line)) break;
    }
    bios_clear();
    color(2);
    bios_gotoxy(20, 12); bios_puts("SYSTEM HALTED.");
    /* returns into boot.s's _halt loop */
}
