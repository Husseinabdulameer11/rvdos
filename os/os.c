/* os.c -- RVDOS 2.0: a CP/M-style operating system for this RV32IM core.
 *
 * Three layers, CP/M's own vocabulary:
 *   BIOS  -- console (scrolling text on the framebuffer, fast cell
 *            renderer), keyboard (small ring buffer, ^C detection) and the
 *            RAM disk. The only code here that touches hardware.
 *   BDOS  -- bdos_dispatch(): the single syscall entry every program calls
 *            through the fixed 0x0004 vector. This is the stable ABI
 *            (syscall.h).
 *   CCP   -- ccp_main(): the command processor. An "A>" prompt; built-in
 *            commands (DIR, TYPE, ERA, REN, PIP, STAT, ...); any other word
 *            runs a transient: a ROM program such as PONG.COM, or a Flint
 *            program such as HELLO.FLT from the RAM disk.
 *
 * On the current Harvard machine the OS and all transients are co-resident
 * in one ROM image, so "launch" is a direct call. When the data/fetch
 * memories are later unified and a loader exists, only the CCP changes
 * (load from disk, then jump) -- the programs and the ABI do not.
 */
#include "syscall.h"
#include "gfx.h"
#include "font.h"
#include "kbd.h"
#include "mini.h"

/* ---- transient program entry points (co-resident for now) ------------- */
